// node scripts/seed-category-descriptions.mjs
// Checks the hand-written category copy in scripts/data/category-descriptions.mjs
// and writes supabase/migrations/010_seed_category_descriptions.sql from it.
// Exits with an error (and writes nothing) when a rule fails.

import { writeFileSync } from 'node:fs'
import { CATEGORIES } from './data/category-descriptions.mjs'
import { checkContent } from '../src/lib/contentRules.js'

const words = (s) => s.trim().split(/\s+/).length
const errors = []
const seen = { slug: new Set(), seo_title: new Set(), seo_description: new Set(), intro: new Set() }

for (const c of CATEGORIES) {
  const where = c.slug
  const fail = (msg) => errors.push(`${where}: ${msg}`)
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(c.slug)) fail('bad slug')
  if (c.seo_title.length < 30 || c.seo_title.length > 53) fail(`seo_title is ${c.seo_title.length} characters (30–53)`)
  if (c.seo_description.length < 140 || c.seo_description.length > 160) fail(`seo_description is ${c.seo_description.length} characters (140–160)`)
  const w = words(c.intro)
  if (w < 70 || w > 150) fail(`intro is ${w} words (70–150)`)
  for (const key of ['slug', 'seo_title', 'seo_description', 'intro']) {
    if (seen[key].has(c[key])) fail(`duplicate ${key}`)
    seen[key].add(c[key])
  }
  const text = { title: c.title, description: [c.seo_description, c.intro, ...c.faq.flatMap((f) => [f.q, f.a])].join(' ') }
  const hits = checkContent(text)
  if (hits.block.length) fail(`blocked theme: ${hits.block.map((h) => h.match).join(', ')}`)
}
if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const rows = CATEGORIES.map((c) =>
  `  (${q(c.slug)}, ${q(c.title)}, ${q(c.intro)}, ${q(c.seo_title)}, ${q(c.seo_description)}, ${q(JSON.stringify(c.faq))}::jsonb, ${c.is_indexable === false ? 'false' : 'true'})`
)
const sql = `-- 010_seed_category_descriptions.sql
-- Generated by scripts/seed-category-descriptions.mjs from
-- scripts/data/category-descriptions.mjs. Re-running it overwrites the same rows.

insert into public.category_descriptions (slug, title, intro, seo_title, seo_description, faq, is_indexable)
values
${rows.join(',\n')}
on conflict (slug) do update set
  title = excluded.title,
  intro = excluded.intro,
  seo_title = excluded.seo_title,
  seo_description = excluded.seo_description,
  faq = excluded.faq,
  is_indexable = excluded.is_indexable;
`
writeFileSync('supabase/migrations/010_seed_category_descriptions.sql', sql)
console.log(`${CATEGORIES.length} categories ok → supabase/migrations/010_seed_category_descriptions.sql`)
